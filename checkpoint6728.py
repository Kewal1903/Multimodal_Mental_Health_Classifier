def ida_star_maze(start, goal, maze, coords):
    # Initialize the starting threshold: f(start) = g(start) + h(start)
    # Since we are at the start, g = 0, so f = h
    threshold = manh_dist(start, goal)
    nodes_expanded = 0

    # 2. The Iterative Deepening Loop
    while True:
        # We start a fresh dfs with just the start node in our path
        curr_path = [start]

        # Run the search algo from prev section
        result, nodes_expanded = search(curr_path, 0, threshold, goal, maze, nodes_expanded)

        # 3. Evaluate the DFS o/p
        if result == "FOUND":
            # Because our search fxn skips curr_path.pop() when it finds the goal,
            # curr_path contains the successful route
            return curr_path, nodes_expanded

        if result == float('inf'):
            # If the min_cost comes back as inf, it means goal was never reached from start
            # i.e. no valid path
            return None, nodes_expanded

        # 4. Increase the threshold for the next iteration
        # 'result' holds the minimum f-cost that exceeded our old threshold
        threshold = result


