def steepest_ascent_hill_climbing(X, y, max_iterations=100):
    num_features = X.shape[1]

    # 1. Generate a random initial state (0s and 1s)
    current_state = np.random.randint(2, size=num_features).tolist()

    # Safety check: Prevent starting with an empty feature set
    if sum(current_state) == 0:
        current_state[np.random.randint(num_features)] = 1

    current_score = evaluate_state(current_state, X, y)
    print(f"Initial State Score: {current_score:.4f} (Features used: {sum(current_state)})")

    history = [(current_state, current_score)]

    # 2. The Hill-Climbing Loop
    for iteration in range(max_iterations):
        neighbors = get_neighbors(current_state)

        best_neighbor = None
        best_neighbor_score = -1.0

        # Evaluate every single neighbor (This is the "Steepest" part)
        for neighbor in neighbors:
            score = evaluate_state(neighbor, X, y)
            if score > best_neighbor_score:
                best_neighbor_score = score
                best_neighbor = neighbor

        # 3. The Peak Check
        # If no neighbor beats our current score, we are at a local maximum. Stop climbing.
        if best_neighbor_score <= current_score:
            print(f"Reached a peak at iteration {iteration}! No better neighbors.")
            break

        # 4. Move Uphill
        current_state = best_neighbor
        current_score = best_neighbor_score
        history.append((current_state, current_score))

        print(f"Iteration {iteration+1}: Jumped to new score {current_score:.4f} (Features used: {sum(current_state)})")

    return current_state, current_score, history


