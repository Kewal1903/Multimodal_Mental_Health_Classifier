# Env Setup
import numpy as np
import random

class WarehouseEnv:
    def __init__(self, grid_size=5):
        self.grid_size = grid_size
        self.start_state = (0, 0)
        self.goal_state = (4, 4)

        # create few obstacles (hard-coded)
        self.obstacles = [(1, 1), (2, 2), (3, 1)]

        # self.state hold the current state/location of the agent
        # At the start (init), the agent is at the start position (0, 0)
        # Hence we set it to self.start_state at the beginning
        # In the later parts of the code, it's used to store the curr state/locn
        self.state = self.start_state # what was the purpose of this?

        # actions: 0: up, 1: down, 2: left, 3: right
        self.action_space = [0, 1, 2, 3]

    def reset(self):
        """Resets the agent to the start state at the start of a new episode"""
        self.state = self.start_state
        return self.state

    def step(self, action):
        """
        Takes an action, updates the state and calculates the reward
        Returns: (next_state, reward, done_flag)
        """

        # Get current state coords
        r, c = self.state

        # 1. Calculate the tentative new position
        if action == 0: # up
            r = max(0, r - 1)
        if action == 1: # down
            r = min(self.grid_size - 1, r + 1)
        if action == 2: # left
            c = max(0, c - 1)
        if action == 3: # right
            c = min(self.grid_size - 1, c + 1)

        next_state = (r, c)

        # 2. Check collision with obstacles
        if next_state in self.obstacles:
            # Hit an obstacle, bounce back to the original state, get -ve reward
            next_state = self.state
            reward = -10
            done = False
        # 3. Check if goal achieved
        elif next_state == self.goal_state:
            # Reached goal, give massive reward, end episode
            reward = 100
            done = True
        # 4. Handle normal case
        else:
            # Normal movement, give small -ve reward to force exploration
            reward = -1
            done = False

        # 5. Update internal state
        self.state = next_state

        # Return (next_state i.e. updated state, reward, done flag)
        return next_state, reward, done


#========================================================================#


class QLearningAgent:
    def __init__(self, env, alpha=0.1, gamma=0.9, epsilon=1.0,
                 epsilon_decay=0.995, min_epsilon=0.01):
        self.env = env
        self.alpha = alpha     # Learning rate
        self.gamma = gamma     # Discount factor (important for future rewards)
        self.epsilon = epsilon # Initial exploration rate (1.0 = 100% random)
        self.epsilon_decay = epsilon_decay
        self.min_epsilon = min_epsilon

        # Initialize the Q-table: a dict mapping (r, c) -> array of 4 Q-values
        self.q_table = {}
        # Iterate over rows
        for r in range(env.grid_size):
            # Iterate over cols
            for c in range(env.grid_size):
                # for (r,c) key, store an array containing 4 zeros
                self.q_table[(r, c)] = np.zeros(len(env.action_space))

    def choose_action(self, state):
        """Epsilon-greedy action selection"""
        # EXPLORE: Roll a random number: If it is less than epsilon,
        # pick a random action
        if random.uniform(0, 1) < self.epsilon:
            return random.choice(self.env.action_space)
        # EXPLOIT : Otherwise, refer the Q-table and pick the action with
        # the largest Q-value
        else:
            return np.argmax(self.q_table[state])

    def learn(self, state, action, reward, next_state):
        """Updates the Q-table using Bellman Equation"""
        # 1. Look ahead to the next state and find the highest possible Q-value
        best_next_action_value = np.max(self.q_table[next_state])

        # 2. Calculate what the Q-value *should* be (the temporal diff target)
        td_target = reward + (self.gamma * best_next_action_value)

        # 3. Calculate the error between old guess and the new target
        td_error = td_target - self.q_table[state][action]

        # 4. Update the Q-Table incrementally using the learning rate (alpha)
        self.q_table[state][action] += self.alpha * td_error

    def decay_epsilon(self):
        """Gradually reduce the exploration to transition into exploitation"""
        self.epsilon = max(self.min_epsilon, self.epsilon * self.epsilon_decay)


