def manh_dist_8_puzzle(curr_state, goal_state):
    """
    Calculates the total Manhattan distance for the 8-puzzle.
    Converts 1D tuple indices into 2D (row, col) coordinates.
    """
    total_dist = 0
    # We check tiles 1 through 8 (ignoring the blank tile 0)
    for tile in range(1, 9):
        # Find the index in the current state and goal state
        curr_idx = curr_state.index(tile)
        goal_idx = goal_state.index(tile)

        # Convert 1D index to 2D (row, col) coordinates
        # Row = idx // 3, Col = idx % 3
        curr_row, curr_col = curr_idx // 3, curr_idx % 3
        goal_row, goal_col = goal_idx // 3, goal_idx % 3

        # Calculate Manhattan distance for this specific tile
        dist = abs(curr_row - goal_row) + abs(curr_col - goal_col)
        total_dist += dist

    return total_dist


