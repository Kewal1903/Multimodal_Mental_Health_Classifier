class Node:
    def __init__(self, state, parent=None, g=0, h=0):
        self.state = state
        self.parent = parent
        self.g = g
        self.h = h
        self.f = g + h

        # We need to track children so we know if this node is a leaf
        self.children = []

        # This holds the "backed up" f-cost if a child gets pruned
        self.forgotten_f = float('inf')

    def get_f(self):
        """
        Returns the effective f-cost.
        If this node has forgotten a child, its f-cost is the MINIMUM
        of its normal f-cost and its forgotten child's f-cost.
        """
        # If it has no children in memory, but has a forgotten f-cost,
        # it acts as a proxy for that pruned branch.
        if not self.children and self.forgotten_f != float('inf'):
            return max(self.f, self.forgotten_f)

        # Otherwise, its f-cost is the lowest f-cost of its current children
        if self.children:
            return min([child.get_f() for child in self.children])

        return self.f

    def get_path(self):
        """Helper to trace back to the start node."""
        path = []
        curr = self
        while curr:
            path.append(curr.state)
            curr = curr.parent
        return path[::-1] # Reverse it so it goes Start -> Goal


