"""# RL Traffic Agent"""

import numpy as np
import random

class TrafficEnv:
    def __init__(self, max_cars=5):
        # We cap the cars at max_cars to keep Q-table manageable
        # State represents: (North, South, East, West) queues
        self.max_cars = max_cars

        # Actions: 0 -> North/South Green, 1 -> Left/Right Green
        self.action_space = [0, 1]

        # Start with an empty intersection
        self.state = (0, 0, 0, 0)

        # Track metrics for eval later
        self.total_throughput = 0

    def reset(self):
        """Empties the intersection to start a new episode"""
        self.state = (0, 0, 0, 0)
        self.total_throughput = 0
        return self.state

    def step(self, action):
        """Processes one time step"""
        n, s, e, w = self.state
        # Keep a variable to track the total no. of cars passed in this ep
        cars_passed = 0

        # 1. Let cars pass the intersection on green light
        # Lets assume up to 2 cars can pass thru the light per time step
        pass_rate = 2

        if action == 0: # North/South Green
            # Get no. of cars passed
            passed_n = min(n, pass_rate)
            passed_s = min(s, pass_rate)
            # Update the no. of cars waiting
            n -= passed_n
            s -= passed_s
            # Update the total no. of cars passed
            cars_passed = passed_n + passed_s
        else: # East/West Green
            passed_e = min(e, pass_rate)
            passed_w = min(w, pass_rate)

            e -= passed_e
            w -= passed_w

            cars_passed = passed_e + passed_w

        self.total_throughput += cars_passed

        # 2. New random traffic arrives at the intersxn
        # 30% chance for 1 new car to arrive
        arrival_prob = 0.3

        n = min(self.max_cars, n + (1 if random.random() < arrival_prob else 0))
        s = min(self.max_cars, s + (1 if random.random() < arrival_prob else 0))
        e = min(self.max_cars, e + (1 if random.random() < arrival_prob else 0))
        w = min(self.max_cars, w + (1 if random.random() < arrival_prob else 0))

        # 3. Calculate the reward
        # Reward is the -ve of the total cars waiting.
        # Note that at this point of code, n, s, e, w values have been updated
        total_waiting = n + s + e + w
        reward = -total_waiting

        # Update the current state
        self.state = (n, s, e, w)

        # We will run this continuously in loop so 'done' is false here
        # (we will manually stop the episode after a few steps)
        done = False

        return self.state, reward, done


