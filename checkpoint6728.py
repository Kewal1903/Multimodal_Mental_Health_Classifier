def get_valid_moves(idx):
    moveset = []

    # UP move can be performed as long as the agent is not in top row
    # For up, do idx - 3
    if idx > 2:
        moveset.append(-3)
    # DOWN move can be performed as long as the agent is not in the btm row
    # For DOWN, do idx + 3
    if idx < 6:
        moveset.append(3)
    # LEFT can be done if agent is not in leftmost col already
    # For LEFT do idx - 1
    if idx not in [0, 3, 6]:
        moveset.append(-1)
    # RIGHT can be done if the agent is not in rightmost col already
    # For RIGHT do idx + 1
    if idx not in [2, 5, 8]:
        moveset.append(1)

    return moveset


#=======================================================================#


def bfs_8_puzzle(start, goal):
    # Instantiate a visited set
    visited = set()
    # Instantiate a deque
    dq = deque()
    # Append the start state to the dq - pass it as a list
    # Here each **tuple** (not a single number) is a node
    # And the deque as always stores paths which in this case are lists containing tuples
    dq.append([start])
    # Keep a track of the nodes expanded
    nodes_expanded = 0

    # Iteratively handle paths in the dq
    while dq:
        # Fetch the current path
        path = dq.popleft()
        # Fetch the current node
        node = path[-1]

        # Check if the node is the goal
        if node == goal:
            return path, nodes_expanded

        # If the node is not goal, check if it has been already visited
        if node not in visited:
            # Since we visited the node now, add it to visited
            visited.add(node)
            # Add count to nodes expanded
            nodes_expanded += 1
            # Get the index where 0 is present in the node - for neighbour calc
            zero_idx = node.index(0)
            # Get the valid moves list for the idx
            moves = get_valid_moves(zero_idx)

            # Iteratively perform all moves (same as visiting all neighbours)
            # To perform a move, you will have to swap the ele in new index with 0
            # To do this, convert tuple to list first
            # After performing swap/move, convert list back to tuple and append to path
            for move in moves:
                # convert to list
                new_node = list(node)
                # Calculate new idx: zero_idx + move
                new_idx = zero_idx + move
                # perform swap
                new_node[new_idx], new_node[zero_idx] = new_node[zero_idx], new_node[new_idx]
                # Convert the list back to a tuple
                new_node = tuple(new_node)
                # Add the new node to a new path which is a copy of the current path
                new_path = list(path)
                # Append new node to new path
                new_path.append(new_node)
                # Append new path to sq
                dq.append(new_path)

    return None, nodes_expanded


