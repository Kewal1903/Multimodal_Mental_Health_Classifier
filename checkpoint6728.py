def search_8_puzzle(curr_path, g, threshold, goal, nodes_expanded):
    # 1. Evaluate the current state
    curr_node = curr_path[-1]
    f = g + manh_dist_8_puzzle(curr_node, goal)

    # BAse case 1: cost exceeds the threshold
    if f > threshold:
        return f, nodes_expanded

    # Base case 2: curr node is goal
    if curr_node == goal:
        return "FOUND", nodes_expanded

    min_cost = float('inf')

    # 2. Generate neighbours using the fxn
    zero_idx = curr_node.index(0)
    moves = get_valid_moves(zero_idx)

    for move in moves:
        # Perform swap to get the new state
        new_node_list = list(curr_node)
        # calculate new_idx
        new_idx = zero_idx + move
        # swap
        new_node_list[zero_idx], new_node_list[new_idx] = curr_node[new_idx], curr_node[zero_idx]
        # Tuple
        new_node = tuple(new_node_list)

        if new_node not in curr_path:
            curr_path.append(new_node)
            nodes_expanded += 1

            # Recursive step: g+1
            result, nodes_expanded = search_8_puzzle(curr_path, g+1, threshold, goal, nodes_expanded)

            if result == "FOUND":
                return "FOUND", nodes_expanded

            if result < min_cost:
                min_cost = result

            # BACKTRACK
            curr_path.pop()

    return min_cost, nodes_expanded


