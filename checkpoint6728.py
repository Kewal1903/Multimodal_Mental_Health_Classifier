def get_neighbors(state):
    """
    Generates all possible neighbors by flipping exactly one bit
    in the current binary state array.
    """
    neighbors = []
    for i in range(len(state)):
        # Create a fresh copy of the current state
        neighbor = list(state)

        # Flip the i-th bit (1 becomes 0, 0 becomes 1)
        neighbor[i] = 1 - neighbor[i]

        neighbors.append(neighbor)

    return neighbors


