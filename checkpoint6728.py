def search(curr_path, g, threshold, goal, maze, nodes_expanded):
    """
    Recursive DFS that explores paths up to a specific f-cost threshold.
    Returns: (Result, updated_nodes_expanded)
    Result can be "FOUND" or the min f-cost that exceeded the threshold.
    """
    # The curr node that we are evaluating is the last node in the path
    curr_node = curr_path[-1]

    # Calculate f(n) = g(n) + h(n)
    f = g + manh_dist(curr_node, goal)

    # 1. Base case: Threshold exceeded
    # If this node's cost is too high, prune it
    # We return 'f' so that the outer loop knows what to increase the threshold to next time
    if f > threshold:
        return f, nodes_expanded

    # 2. Base case: Goal Found
    if curr_node == goal:
        return "FOUND", nodes_expanded

    # 3. Recursive DFS expansion
    # We need to track the lowest cost among all pruned branches
    # So we will start with a very high min cost so that it gets updated easily
    min_cost = float('inf')

    for neighbour in maze[curr_node]:
        # Mem efficient cycle prevention: only check current path
        if neighbour not in curr_path:
            # Expand node
            curr_path.append(neighbour)
            nodes_expanded += 1

            # Recursive step: g always increases by 1 when a node is expanded
            result, nodes_expanded = search(curr_path, g+1, threshold, goal, maze, nodes_expanded)

            # If the recursive call found goal, unwind stack immediately
            if result == "FOUND":
                return "FOUND", nodes_expanded

            # If not found update the min_cost with the pruned value
            if result < min_cost:
                min_cost = result

            # BACTRACK: Remove neighbour before trying next one
            curr_path.pop()

    return min_cost, nodes_expanded


