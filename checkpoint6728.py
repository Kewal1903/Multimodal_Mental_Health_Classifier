class UCBAgent:
    def __init__(self, k_arms=5, c=2.0):
        self.k = k_arms
        self.c = c # Exploration param

        self.q_values = np.zeros(self.k)
        self.action_counts = np.zeros(self.k)

        # Keep track of the steps taken so far (new)
        self.total_steps = 0

    def choose_action(self):
        """Action based on the upper confidence bound formula"""
        self.total_steps += 1

        # If there is an ad that hasn't show up yet, we must show it first
        # to get the baseline data
        # This prevents 0 in UCB calc
        if 0 in self.action_counts:
            # np.where returns a tuple, [0][0] gets the first index
            # where the count is zero
            return np.where(self.action_counts == 0)[0][0]

        # Calculate UCB for all ads
        # Formula: Q + c * sqrt(ln(t) / N)
        exploration_bonus = self.c * np.sqrt(np.log(self.total_steps) / self.action_counts)
        ucb_values = self.q_values + exploration_bonus

        # Return the action with the highest UCB value
        return np.argmax(ucb_values)

    def learn(self, action, reward):
        """Exactly the same learning rule as epsilon-greedy"""
        self.action_counts[action] += 1
        n = self.action_counts[action]
        old_q = self.q_values[action]

        self.q_values[action] = old_q + (1.0 / n) * (reward - old_q)


