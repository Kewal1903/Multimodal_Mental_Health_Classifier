def sma_star_maze(start, goal, maze, coords, memory_limit=5):
    # Initialize the start node
    start_h = manh_dist(start, goal)
    start_node = Node(state=start, g=0, h=start_h)

    # The frontier holds all our current leaf nodes
    frontier = [start_node]
    nodes_expanded = 0
    current_memory = 1  # We currently have 1 node in memory

    while frontier:
        # 1. Find the BEST node to expand (Lowest f-cost)
        # We sort ascending, so the best node is at index 0
        frontier.sort(key=lambda n: n.get_f())
        best_node = frontier.pop(0)

        # 2. Base Case: Goal Reached
        if best_node.state == goal:
            return best_node.get_path(), nodes_expanded

        # 3. Expand the best node
        nodes_expanded += 1
        path_so_far = best_node.get_path() # For cycle prevention

        for neighbour in maze[best_node.state]:
            if neighbour not in path_so_far:
                child_g = best_node.g + 1
                child_h = manh_dist(neighbour, goal)

                # Create the child and link it to the parent
                child = Node(state=neighbour, parent=best_node, g=child_g, h=child_h)
                best_node.children.append(child)

                # Add child to our active frontier
                frontier.append(child)
                current_memory += 1

        # 4. The SMA* Memory Manager (Pruning)
        # If expanding those neighbors pushed us over the memory limit, we must prune.
        while current_memory > memory_limit:
            # Sort descending, so the WORST node (highest f-cost) is at index 0
            frontier.sort(key=lambda n: n.get_f(), reverse=True)
            worst_node = frontier.pop(0)

            parent = worst_node.parent
            if parent:
                # Remove the worst node from its parent's memory
                parent.children.remove(worst_node)

                # BACKUP COST: The parent remembers the best cost of its forgotten children
                parent.forgotten_f = min(parent.forgotten_f, worst_node.get_f())

                # CRITICAL STEP: If we deleted all of a parent's children,
                # the parent is now a leaf node again! It must go back into the frontier.
                if not parent.children and parent not in frontier:
                    frontier.append(parent)

            # We successfully freed up 1 unit of memory
            current_memory -= 1

    # If the frontier is empty and we haven't found the goal, the maze is impossible
    return None, nodes_expanded


