class EpsilonGreedyAgent:
    def __init__(self, k_arms=5, epsilon=0.1):
        self.k = k_arms
        self.epsilon = epsilon

        # Q-values: Our current estimated q-values for each ad - starts at 0
        self.q_values = np.zeros(self.k)

        # N-values: How many times we have selected each ad - starts at 0
        self.action_counts = np.zeros(self.k)

    def choose_action(self):
        """Epsilon-Greedy action selection"""
        # EXPLORE: Roll a number - if less than epsilon, select random ad
        if np.random.random() < self.epsilon:
            return np.random.randint(self.k)
        # EXPLOIT: Otherwise pick ad with highest estimated Q-value
        else:
            return np.argmax(self.q_values)

    def learn(self, action, reward):
        """Updates the estimated value of the chosen ad using incremental avg"""
        # 1. Increment the count for this action
        self.action_counts[action] += 1

        # 2. Update the q-value for the ad using inc. avg formula
        n = self.action_counts[action]
        old_q = self.q_values[action]

        self.q_values[action] = old_q + (1.0 / n) * (reward - old_q)


