class TrafficQLearningAgent:
    def __init__(self, env, alpha=0.1, gamma=0.9, epsilon=1.0,
                 epsilon_decay=0.99, min_epsilon=0.01):
        self.env = env
        self.alpha = alpha
        self.gamma = gamma
        self.epsilon = epsilon
        self.epsilon_decay = epsilon_decay
        self.min_epsilon = min_epsilon

        # Initialize the Q-table for all 6 * 6 * 6 * 6 possibilities
        # Each key in the Q-table stores a 2-valued array -
        # Q values for action 0 and 1
        self.q_table = {}
        max_c = env.max_cars + 1
        for n in range(max_c):
            for s in range(max_c):
                for e in range(max_c):
                    for w in range(max_c):
                        self.q_table[(n, s, e, w)] = np.zeros(len(env.action_space))

    def choose_action(self, state):
        """Epsilon Greedy Action"""
        if random.uniform(0, 1) < self.epsilon:
            return random.choice(self.env.action_space)
        else:
            return np.argmax(self.q_table[state])

    def learn(self, state, action, reward, next_state):
        """Standard Temporal Difference Update"""
        # Get the best q-value for the next state
        best_next_action_value = np.argmax(self.q_table[next_state])
        # Calculate the actual taget value based on current reward and
        # next state's best q_value (best_next_action_value)
        td_target = reward + (self.gamma * best_next_action_value)
        # Calculate the loss: the target value (actual reward) - curr Q-value
        td_error = td_target - self.q_table[state][action]
        # Update the curr Q-value based on the error calculated
        self.q_table[state][action] += self.alpha * td_error

    def decay_epsilon(self):
        self.epsilon = max(self.min_epsilon, self.epsilon * self.epsilon_decay)


