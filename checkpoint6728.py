def sma_star_8_puzzle(start_state, goal_state, memory_limit=50):
    # 1. Initialize the start node using our Manhattan distance heuristic
    start_h = manh_dist_8_puzzle(start_state, goal_state)
    start_node = Node(state=start_state, g=0, h=start_h)

    frontier = [start_node]
    nodes_expanded = 0
    current_memory = 1

    while frontier:
        # Sort ascending to get the best node (lowest f-cost)
        frontier.sort(key=lambda n: n.get_f())
        best_node = frontier.pop(0)

        # Base Case: Goal Reached
        if best_node.state == goal_state:
            return best_node.get_path(), nodes_expanded

        nodes_expanded += 1
        path_so_far = best_node.get_path()

        # 2. GENERATE NEIGHBORS (The 8-Puzzle Physics)
        zero_idx = best_node.state.index(0)
        moves = get_valid_moves(zero_idx)

        for move in moves:
            # Swap the tiles to create the new state
            new_state_list = list(best_node.state)
            new_idx = zero_idx + move
            new_state_list[zero_idx], new_state_list[new_idx] = new_state_list[new_idx], new_state_list[zero_idx]
            child_state = tuple(new_state_list)

            # Cycle prevention
            if child_state not in path_so_far:
                child_g = best_node.g + 1 # Uniform step cost = 1
                child_h = manh_dist_8_puzzle(child_state, goal_state)

                # Create and link the child node
                child = Node(state=child_state, parent=best_node, g=child_g, h=child_h)
                best_node.children.append(child)

                frontier.append(child)
                current_memory += 1

        # 3. SMA* MEMORY MANAGER
        while current_memory > memory_limit:
            # Sort descending to find the worst node (highest f-cost)
            frontier.sort(key=lambda n: n.get_f(), reverse=True)
            worst_node = frontier.pop(0)

            parent = worst_node.parent
            if parent:
                # Prune the leaf
                parent.children.remove(worst_node)
                # Backup the cost
                parent.forgotten_f = min(parent.forgotten_f, worst_node.get_f())

                # Re-insert parent if it becomes a leaf again
                if not parent.children and parent not in frontier:
                    frontier.append(parent)

            current_memory -= 1

    return None, nodes_expanded


